    private void btnrfidActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnrfidActionPerformed
        // TODO add your handling code here:
    JPanel panel = new JPanel();
    JLabel label = new JLabel("Scan Kartu RFID Anda:");
    JTextField textField = new JTextField(20);

    label.setFont(new Font("Tw Cen MT", Font.BOLD, 20));
    textField.setFont(new Font("Tw Cen MT", Font.PLAIN, 20));

    panel.add(label);
    panel.add(textField);

    int result = JOptionPane.showConfirmDialog(
        this, panel, "Login RFID", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE
    );

    if (result == JOptionPane.OK_OPTION) {
        String inputRFID = textField.getText().trim();

        if (!inputRFID.isEmpty()) {
            try {
                java.sql.Connection conn = Koneksi.getConnection();
                String sql = "SELECT * FROM admin WHERE RFID = ?";
                java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, inputRFID);

                java.sql.ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    String nama = rs.getString("Nama");
                    showWelcomePopup(nama);

                    Menu_Utama menu = new Menu_Utama();
                    menu.setNamaAdminAktif(nama); // kirim nama admin aktif
                    menu.setVisible(true);
                    this.dispose();
                } else {
                    JOptionPane.showMessageDialog(this, "RFID tidak dikenali!");
                }

                rs.close();
                pst.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "RFID tidak boleh kosong!");
        }
    }


    }//GEN-LAST:event_btnrfidActionPerformed

    private void btnmasukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnmasukActionPerformed
        // TODO add your handling code here:
    String username = fieldusername.getText();
    String password = fieldpassword.getText();

    try {
        java.sql.Connection conn = Koneksi.getConnection();
        String sql = "SELECT * FROM admin WHERE Username=? AND Password=?";
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, username);
        pst.setString(2, password);

        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            String nama = rs.getString("Nama");
            showWelcomePopup(nama);

            Menu_Utama menu = new Menu_Utama();
            menu.setNamaAdminAktif(nama); // kirim nama admin aktif
            menu.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Login Gagal! Username atau Password salah.");
        }

        rs.close();
        pst.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
    }



      
    }//GEN-LAST:event_btnmasukActionPerformed

